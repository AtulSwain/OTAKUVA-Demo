/**
 * OTAKUVA — one-time SQLite → PostgreSQL data migration.
 *
 * Copies every row of every table from `prisma/dev.db` (SQLite) into the
 * PostgreSQL database `DATABASE_URL` (in `.env`/the environment) now
 * points at, preserving primary keys and every foreign key relationship
 * exactly as they were. Run this once, after `prisma migrate deploy` has
 * already created the (empty) Postgres schema — see
 * docs/production/RUNBOOK.md's Postgres section for the full cutover
 * sequence this script is one step of.
 *
 * Usage:
 *   PG_SUPERUSER_URL="postgresql://postgres:<password>@127.0.0.1:5432/otakuva" \
 *     npx tsx scripts/migrate_sqlite_to_postgres.ts            (dry run — counts only, no writes)
 *   PG_SUPERUSER_URL="..." npx tsx scripts/migrate_sqlite_to_postgres.ts --apply
 *
 * Why a superuser URL, separate from the app's normal DATABASE_URL: this
 * script disables trigger firing for the duration of the load
 * (`SET LOCAL session_replication_role = replica`, transaction-scoped),
 * which is what lets it insert every table in one pass without first
 * topologically sorting ~120 models by foreign-key dependency — Postgres
 * simply doesn't check FK constraints while replication-role triggers are
 * off. Only a superuser (or the table owner, for user triggers only — not
 * the internal FK-enforcement triggers) can set that. The app's own
 * low-privilege role is never used for this, and never needs this
 * privilege at runtime.
 *
 * How field values are read correctly (not reinvented here): rather than
 * hand-writing SQLite→Postgres type coercion for every column (booleans
 * are 0/1 in SQLite, DateTime is TEXT, etc.), this generates and imports a
 * second, throwaway Prisma Client against the *same* schema shape but with
 * the datasource still pointed at sqlite (written to
 * prisma/_sqlite_snapshot.prisma — auto-generated by this script on every
 * run from the current prisma/schema.prisma, deleted afterward, never
 * committed; see ensureSqliteSnapshotClient() below) — that client reads
 * prisma/dev.db with fully-deserialized JS values (real Date objects, real
 * booleans). The normal (now-postgresql) `@prisma/client` is only used to
 * introspect the shared schema shape via its DMMF; the actual writes go
 * through node-postgres directly (see above, needs the trigger-disabling
 * superuser connection Prisma's own client can't use).
 *
 * Safety: refuses to run if any target table is non-empty, unless --force
 * is also passed (which TRUNCATEs every target table first — this is a
 * one-time cutover script, not an incremental sync; never mixes with live
 * writes to prisma/dev.db). Every table is copied inside one transaction:
 * either the whole database lands, or (on any error) none of it does.
 */

import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { Client } from 'pg';
import { Prisma } from '@prisma/client';

const APPLY = process.argv.includes('--apply');
const FORCE = process.argv.includes('--force');
const REPO_ROOT = path.resolve(__dirname, '..');
const SQLITE_DB_PATH = process.env.SQLITE_DB_PATH || path.join(REPO_ROOT, 'prisma', 'dev.db');
const PG_SUPERUSER_URL = process.env.PG_SUPERUSER_URL;

const BATCH_SIZE = 500;

const SNAPSHOT_SCHEMA_PATH = path.join(REPO_ROOT, 'prisma', '_sqlite_snapshot.prisma');
const SNAPSHOT_CLIENT_DIR = path.join(REPO_ROOT, 'node_modules', '.prisma', 'client-sqlite-snapshot');

/**
 * Regenerates the sqlite-flavored Prisma Client from whatever
 * prisma/schema.prisma currently is (swapping only the datasource
 * provider + generator output), so this script stays correct even if the
 * schema has evolved since the Postgres migration — it never trusts a
 * stale committed copy. Writes prisma/_sqlite_snapshot.prisma as a
 * transient build artifact (gitignored) and removes it when done.
 */
function ensureSqliteSnapshotClient(): void {
  const currentSchema = fs.readFileSync(path.join(REPO_ROOT, 'prisma', 'schema.prisma'), 'utf8');
  const snapshotSchema = currentSchema
    .replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"')
    .replace(
      /generator client \{\s*provider = "prisma-client-js"/,
      `generator client {\n  provider = "prisma-client-js"\n  output   = "../node_modules/.prisma/client-sqlite-snapshot"`
    );
  fs.writeFileSync(SNAPSHOT_SCHEMA_PATH, snapshotSchema);

  try {
    const prismaCli = require.resolve('prisma/build/index.js', { paths: [REPO_ROOT] });
    execFileSync(process.execPath, [prismaCli, 'generate', '--schema', SNAPSHOT_SCHEMA_PATH], { stdio: 'pipe' });
  } finally {
    fs.rmSync(SNAPSHOT_SCHEMA_PATH, { force: true });
  }
}

// Tables Prisma manages itself — never part of the application schema, never copied.
const SKIP_TABLES = new Set(['_prisma_migrations']);

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

interface ModelPlan {
  modelName: string; // Prisma model name, e.g. "AnimeRating"
  delegateName: string; // prisma client property name, e.g. "animeRating"
  tableName: string; // actual DB table name (respects @@map, defaults to modelName)
  fields: { jsName: string; columnName: string }[]; // scalar fields only, in declaration order
}

function buildModelPlans(): ModelPlan[] {
  const plans: ModelPlan[] = [];
  for (const model of Prisma.dmmf.datamodel.models) {
    const tableName = model.dbName || model.name;
    if (SKIP_TABLES.has(tableName)) continue;
    const fields = model.fields
      .filter((f) => f.kind === 'scalar')
      .map((f) => ({ jsName: f.name, columnName: f.dbName || f.name }));
    const delegateName = model.name.charAt(0).toLowerCase() + model.name.slice(1);
    plans.push({ modelName: model.name, delegateName, tableName, fields });
  }
  return plans;
}

function toSqlValue(v: unknown): unknown {
  if (v instanceof Date) return v; // pg driver serializes Date correctly
  return v; // string / number / boolean / null pass through as-is
}

async function main() {
  console.log(`migrate_sqlite_to_postgres — ${APPLY ? 'APPLY (will write)' : 'DRY RUN (pass --apply to write)'}${FORCE ? ' [--force: will TRUNCATE target tables first]' : ''}\n`);
  console.log(`Source (SQLite): ${SQLITE_DB_PATH}`);

  if (!PG_SUPERUSER_URL) {
    throw new Error('PG_SUPERUSER_URL is required (a superuser connection string to the target Postgres database) — see this file\'s header comment.');
  }

  console.log('Regenerating the sqlite-flavored Prisma Client from the current schema...');
  ensureSqliteSnapshotClient();

  // Sqlite reader: the generated snapshot client, pointed explicitly at
  // prisma/dev.db regardless of what DATABASE_URL currently is.
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { PrismaClient: SqlitePrismaClient } = require(SNAPSHOT_CLIENT_DIR);
  const sqlite = new SqlitePrismaClient({
    datasources: { db: { url: `file:${SQLITE_DB_PATH.replace(/\\/g, '/')}` } },
  });

  const pg = new Client({ connectionString: PG_SUPERUSER_URL });
  await pg.connect();
  console.log(`Target (Postgres): ${await pg.query('select current_database() as db').then((r) => r.rows[0].db)}\n`);

  const plans = buildModelPlans();
  console.log(`${plans.length} tables to migrate.\n`);

  // ---- Pre-flight: source counts, target emptiness ----
  const sourceCounts = new Map<string, number>();
  for (const plan of plans) {
    const delegate = (sqlite as any)[plan.delegateName];
    const count: number = await delegate.count();
    sourceCounts.set(plan.modelName, count);
  }

  const nonEmptyTargets: string[] = [];
  for (const plan of plans) {
    const res = await pg.query(`SELECT COUNT(*)::int AS c FROM ${quoteIdent(plan.tableName)}`);
    if (res.rows[0].c > 0) nonEmptyTargets.push(`${plan.tableName} (${res.rows[0].c} rows)`);
  }

  const totalSourceRows = [...sourceCounts.values()].reduce((a, b) => a + b, 0);
  console.log(`Source row total: ${totalSourceRows}`);
  console.log(`Non-empty target tables: ${nonEmptyTargets.length ? nonEmptyTargets.join(', ') : '(none)'}\n`);

  if (nonEmptyTargets.length > 0 && !FORCE) {
    throw new Error(
      `Target Postgres database already has data in ${nonEmptyTargets.length} table(s). ` +
        `Refusing to proceed without --force (which TRUNCATEs every target table first). ` +
        `If this is intentional (re-running the migration), re-run with --apply --force.`
    );
  }

  if (!APPLY) {
    console.log('Dry run only — no rows were written. Re-run with --apply (and PG_SUPERUSER_URL) to execute.');
    await pg.end();
    await sqlite.$disconnect();
    return;
  }

  // ---- Migrate ----
  await pg.query('BEGIN');
  try {
    // Trigger firing off for this transaction only — including the
    // internal triggers Postgres uses to enforce FK constraints. Lets
    // every table load in any order without a topological sort.
    await pg.query('SET LOCAL session_replication_role = replica');

    if (FORCE && nonEmptyTargets.length > 0) {
      const allTables = plans.map((p) => quoteIdent(p.tableName)).join(', ');
      console.log('--force: truncating all target tables first...');
      await pg.query(`TRUNCATE TABLE ${allTables} RESTART IDENTITY`);
    }

    for (const plan of plans) {
      const total = sourceCounts.get(plan.modelName) || 0;
      if (total === 0) {
        console.log(`  ${plan.tableName}: 0 rows — skipped`);
        continue;
      }

      // Read the whole table at once — every table here is at most a few
      // thousand rows (this is a ~17MB SQLite file, not a data warehouse),
      // so there's no need for cursor pagination on the read side. A
      // cursor keyed on `id` also wouldn't work uniformly: 10 of the 119
      // models are composite-key join tables with no `id` field at all
      // (AnimeGenre, AnimeStudio, Follow, ...). Batching still happens on
      // the write side, below, to keep each INSERT statement a reasonable
      // size.
      const delegate = (sqlite as any)[plan.delegateName];
      const rows: Record<string, unknown>[] = await delegate.findMany();
      const columns = plan.fields.map((f) => f.columnName);
      let copied = 0;

      for (let i = 0; i < rows.length; i += BATCH_SIZE) {
        const batch = rows.slice(i, i + BATCH_SIZE);
        const valueRows: unknown[][] = batch.map((row) => plan.fields.map((f) => toSqlValue(row[f.jsName])));

        const placeholders: string[] = [];
        const params: unknown[] = [];
        let paramIndex = 1;
        for (const valueRow of valueRows) {
          const rowPlaceholders = valueRow.map(() => `$${paramIndex++}`);
          placeholders.push(`(${rowPlaceholders.join(', ')})`);
          params.push(...valueRow);
        }

        const sql = `INSERT INTO ${quoteIdent(plan.tableName)} (${columns.map(quoteIdent).join(', ')}) VALUES ${placeholders.join(', ')}`;
        await pg.query(sql, params);
        copied += batch.length;
      }

      console.log(`  ${plan.tableName}: ${copied}/${total} rows copied`);
    }

    await pg.query('COMMIT');
    console.log('\nTransaction committed.');
  } catch (err) {
    await pg.query('ROLLBACK');
    console.error('\nMigration failed — transaction rolled back, target database unchanged:', err);
    throw err;
  }

  // ---- Verify ----
  console.log('\nVerifying row counts...');
  let mismatches = 0;
  for (const plan of plans) {
    const res = await pg.query(`SELECT COUNT(*)::int AS c FROM ${quoteIdent(plan.tableName)}`);
    const expected = sourceCounts.get(plan.modelName) || 0;
    const actual = res.rows[0].c;
    if (actual !== expected) {
      mismatches++;
      console.error(`  MISMATCH ${plan.tableName}: expected ${expected}, got ${actual}`);
    }
  }
  if (mismatches === 0) {
    console.log('All table counts match. Migration verified.');
  } else {
    console.error(`\n${mismatches} table(s) mismatched — investigate before trusting this data.`);
  }

  await pg.end();
  await sqlite.$disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
