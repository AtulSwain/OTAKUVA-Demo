/**
 * Converts the seal kanji into SVG path data so seals render identically on
 * every device, with no dependency on a Japanese font being installed/loaded.
 *
 *   npx tsx scripts/badges/build_glyphs.ts [path/to/NotoSerifJP-Bold.(ttf|otf|woff)]
 *
 * With no argument it downloads a subset of Noto Serif JP Bold (SIL OFL 1.1)
 * containing exactly the characters found in src/lib/badges/tiers.ts, from
 * Google Fonts, and writes src/lib/badges/glyphPaths.ts (committed).
 * Re-run whenever a tier's `kanji` changes.
 */
import fs from 'fs';
import path from 'path';
import opentype from 'opentype.js';
import { TIERS } from '../../src/lib/badges/tiers';

const OUT = path.join(__dirname, '../../src/lib/badges/glyphPaths.ts');
const chars = Array.from(new Set(TIERS.flatMap((t) => Array.from(t.kanji))));

async function loadFont(arg?: string): Promise<opentype.Font> {
  if (arg) return opentype.parse(fs.readFileSync(arg).buffer.slice(0) as ArrayBuffer);
  const css = await (
    await fetch(
      `https://fonts.googleapis.com/css2?family=Noto+Serif+JP:wght@700&text=${encodeURIComponent(chars.join(''))}`,
      // An old UA makes Google serve woff (opentype.js cannot read woff2).
      { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 6.1) AppleWebKit/534.24 Chrome/11.0.696.34 Safari/534.24' } }
    )
  ).text();
  const url = /url\(([^)]+)\)/.exec(css)?.[1];
  if (!url) throw new Error('No font URL in Google Fonts response');
  const buf = await (await fetch(url)).arrayBuffer();
  return opentype.parse(buf);
}

(async () => {
  const font = await loadFont(process.argv[2]);
  const upm = font.unitsPerEm;
  const entries: string[] = [];
  for (const ch of chars) {
    const glyph = font.charToGlyph(ch);
    if (!glyph || glyph.index === 0) throw new Error(`Font has no glyph for ${ch}`);
    // Normalise to a 1000-unit em, y-down, baseline at y=0 (opentype.js already flips y).
    const scale = 1000 / upm;
    const p = glyph.getPath(0, 0, upm);
    const bb = p.getBoundingBox();
    const scaled = new (opentype as any).Path();
    scaled.commands = p.commands.map((c: any) => {
      const o = { ...c };
      for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) if (k in o) o[k] = o[k] * scale;
      return o;
    });
    entries.push(
      `  ${JSON.stringify(ch)}: { d: ${JSON.stringify(scaled.toPathData(1))}, x1: ${Math.round(bb.x1 * scale)}, y1: ${Math.round(bb.y1 * scale)}, x2: ${Math.round(bb.x2 * scale)}, y2: ${Math.round(bb.y2 * scale)} },`
    );
  }
  fs.writeFileSync(
    OUT,
    `/* GENERATED by scripts/badges/build_glyphs.ts — do not edit.\n * Noto Serif JP Bold (SIL OFL 1.1), outlined. 1000-unit em, y-down, baseline y=0.\n * x1..y2 is each glyph's ink bounding box, used to centre it inside a seal. */\n\nexport interface GlyphPath { d: string; x1: number; y1: number; x2: number; y2: number }\n\nexport const GLYPHS: Record<string, GlyphPath> = {\n${entries.join('\n')}\n};\n`
  );
  console.log(`Wrote ${chars.length} glyphs to ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
